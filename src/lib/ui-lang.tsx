type Ui = {
  agent: boolean;
  english: boolean;
  lang: "fr" | "en";
  setLang: (lang: "fr" | "en") => void;
  t: (value: string) => string;
};

const Ctx = createContext<Ui>({
  agent: false,
  english: false,
  lang: "fr",
  setLang: () => {},
  t: (value) => value,
});

export function UiLangProvider({
  role,
  children,
}: {
  role: string | undefined;
  children: ReactNode;
}) {
  const [lang, setLangState] = useState<"fr" | "en">("fr");
  useEffect(() => {
    const saved = localStorage.getItem("sp_agent_lang") || localStorage.getItem("sp_lang");
    if (saved === "en") setLangState("en");
  }, []);
  function setLang(next: "fr" | "en") {
    setLangState(next);
    localStorage.setItem("sp_agent_lang", next);
  }
  const english = role === "agent" && lang === "en";
  const t = (value: string) => (english && AGENT_EN[value]) || value;
  return <Ctx.Provider value={{ agent: role === "agent", english, lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useUi() {
  return useContext(Ctx);
}
