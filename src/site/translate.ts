function norm(value: string) {
  return value.replace(/[\u00a0\u202f]/g, " ").replace(/’/g, "'").replace(/\s+/g, " ").trim();
}

const MAP = new Map<string, string>();
for (const [key, value] of Object.entries(RAW)) MAP.set(norm(key), value);

export function translateDom(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes: Text[] = [];
  let current = walker.nextNode();
  while (current) {
    nodes.push(current as Text);
    current = walker.nextNode();
  }
  for (const node of nodes) {
    const raw = node.textContent ?? "";
    const next = MAP.get(norm(raw));
    if (!next) continue;
    const lead = raw.match(/^\s*/)?.[0] ?? "";
    const tail = raw.match(/\s*$/)?.[0] ?? "";
    if (`${lead}${next}${tail}` !== raw) node.textContent = `${lead}${next}${tail}`;
  }
  for (const el of root.querySelectorAll<HTMLElement>("[placeholder],[aria-label],[alt],[title]")) {
    for (const attr of ["placeholder", "aria-label", "alt", "title"] as const) {
      const value = el.getAttribute(attr);
      if (!value) continue;
      const next = MAP.get(norm(value));
      if (next) el.setAttribute(attr, next);
    }
  }
}

